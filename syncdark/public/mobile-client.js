(() => {
  'use strict';
  const $ = (s) => document.querySelector(s);
  const page = $('#mobileapp');
  if (!page || page.dataset.mobileReady === '1') return;
  page.dataset.mobileReady = '1';

  const fallbackVersion = 'v0.6.0.1';
  const targetVersionFormat = /^v\d+\.\d+\.\d+\.\d+$/;
  const text = (id, value) => { const el = $('#' + id); if (el) el.textContent = value; };
  const nativeUpdater = window.SyncAndroidUpdater || null;
  let latestApk = null;
  let installed = null;
  let pendingNativeInstaller = false;

  function setProgress(percent, status, title) {
    const progress = $('#appProgress');
    const statusEl = $('#appDownloadStatus');
    const progressText = $('#appProgressText');
    const bounded = Math.max(0, Math.min(100, percent));
    if (progress) {
      progress.style.width = bounded + '%';
      const track = progress.closest('[role="progressbar"]');
      if (track) track.setAttribute('aria-valuenow', String(bounded));
    }
    if (statusEl) statusEl.textContent = status;
    if (progressText) progressText.textContent = percent < 0 ? '处理中' : bounded + '%';
    if (title) text('appDownloadTitle', title);
  }

  // Called by the native Android bridge. Values are generated by the native downloader.
  window.syncAndroidDownloadProgress = (percent, status) => {
    const value = Number.isFinite(Number(percent)) ? Number(percent) : 0;
    setProgress(value, String(status || '正在处理更新…'), value >= 100 ? '安装包已准备好' : '正在下载更新');
    if (/安装包已下载|安装未知应用|系统安装界面/.test(String(status))) {
      pendingNativeInstaller = true;
      const btn = $('#appInstall');
      if (btn) btn.textContent = '安装已下载的更新';
    }
    if (/校验失败|更新失败|无效|HTTP \d{3}/.test(String(status))) {
      const btn = $('#appInstall');
      if (btn) { btn.disabled = false; btn.textContent = '重试下载安装'; }
    }
  };

  function readInstalledVersion() {
    if (!nativeUpdater || typeof nativeUpdater.getInstalledVersionInfo !== 'function') return null;
    try {
      const info = JSON.parse(nativeUpdater.getInstalledVersionInfo());
      if (Number.isSafeInteger(Number(info.versionCode)) && Number(info.versionCode) > 0) return {
        versionName: String(info.versionName || fallbackVersion),
        versionCode: Number(info.versionCode)
      };
    } catch (_) {}
    return null;
  }

  function versionSummary() {
    if (!latestApk) return;
    if (installed) {
      text('appCurrent', installed.versionName);
      text('appLatest', latestApk.versionName);
      const newer = latestApk.versionCode > installed.versionCode;
      text('appVersionState', newer
        ? '发现新版本：' + installed.versionName + ' → ' + latestApk.versionName
        : latestApk.versionCode === installed.versionCode
          ? '当前已是最新版本。'
          : '服务器提供的版本低于已安装版本，已阻止降级更新。');
      text('appUpdateText', newer
        ? '新版本已签名并提供完整性校验。点击下方按钮下载，下载完成后将打开 Android 系统安装确认页。'
        : latestApk.versionCode === installed.versionCode
          ? '目前无需更新。仍可重新下载安装包，但应用不会自动降级。'
          : '为保护现有安装，暂不允许安装较旧版本。');
      const btn = $('#appInstall');
      if (btn) btn.textContent = newer ? '⇩　下载并安装更新' : '⇩　获取 Android 安装包';
    } else {
      text('appCurrent', '未检测本机');
      text('appLatest', latestApk.versionName);
      text('appVersionState', '网页已取得最新 APK 版本；在 Android 客户端内可比较已安装版本并启动更新。');
      text('appUpdateText', '浏览器下载完成后需从通知栏或文件管理中打开安装包；网页无法自动越过 Android 系统安装确认。');
    }
  }

  async function loadApkVersion() {
    const response = await fetch('/api/android/version?check=' + Date.now(), { cache: 'no-store' });
    let data;
    try { data = await response.json(); } catch (_) { data = {}; }
    if (!response.ok || data.status !== 'available') {
      if (data.code === 'release_not_published') throw new Error('正式签名 APK 尚未发布');
      if (data.code === 'release_service_unavailable') throw new Error('版本服务暂时不可用，请检查网络后重试');
      throw new Error('版本检查失败（HTTP ' + response.status + '）');
    }
    if (data.status !== 'available' || !targetVersionFormat.test(String(data.versionName)) ||
        !Number.isSafeInteger(Number(data.versionCode)) || Number(data.versionCode) <= 0 ||
        !/^[a-f0-9]{64}$/i.test(String(data.sha256)) ||
        !Number.isSafeInteger(Number(data.sizeBytes)) || Number(data.sizeBytes) <= 0 ||
        typeof data.downloadUrl !== 'string' || !data.downloadUrl.startsWith('/api/download/android.apk')) {
      throw new Error('安装包版本信息不完整或不符合四段式版本规则');
    }
    latestApk = { ...data, versionCode: Number(data.versionCode), sizeBytes: Number(data.sizeBytes) };
    const size = latestApk.sizeBytes >= 1048576
      ? (latestApk.sizeBytes / 1048576).toFixed(1) + ' MB'
      : Math.ceil(latestApk.sizeBytes / 1024) + ' KB';
    const published = data.publishedAt ? new Date(data.publishedAt).toLocaleString() : '时间未知';
    text('apkVersionInfo', '已发布：' + data.versionName + '（构建号 ' + data.versionCode + '） · ' + size + ' · SHA-256 已登记 · 发布时间：' + published);
    text('apkVersionLabel', data.versionName);
    text('apkBuildLabel', String(data.versionCode));
    text('apkSizeLabel', size);
    setProgress(0, '安装包信息已验证，等待下载', '下载与完整性校验');
    versionSummary();
    return latestApk;
  }

  async function loadVersions() {
    try {
      const response = await fetch('/api/status?version-check=' + Date.now(), { cache: 'no-store' });
      if (!response.ok) throw new Error('status');
      const data = await response.json();
      text('serverVersion', 'SYS.V ' + String(data.serverVersion || '未知'));
    } catch (_) {
      text('serverVersion', '暂不可用');
    }
  }

  async function browserDownload(meta) {
    setProgress(0, '正在连接下载服务器…', '正在下载安装包');
    const url = new URL(meta.downloadUrl, location.origin);
    const response = await fetch(url.href, { cache: 'no-store' });
    if (!response.ok || !response.body) throw new Error('下载服务器暂不可用');
    const reader = response.body.getReader();
    const chunks = [];
    let received = 0;
    while (true) {
      const { done, value } = await reader.read();
      if (done) break;
      chunks.push(value);
      received += value.byteLength;
      const percent = Math.min(99, Math.floor(received * 100 / meta.sizeBytes));
      setProgress(percent, '正在下载：' + (received / 1048576).toFixed(1) + ' / ' + (meta.sizeBytes / 1048576).toFixed(1) + ' MB', '正在下载安装包');
    }
    const blob = new Blob(chunks, { type: 'application/vnd.android.package-archive' });
    if (blob.size !== meta.sizeBytes) throw new Error('下载大小与登记值不一致，已取消保存');
    const digest = await crypto.subtle.digest('SHA-256', await blob.arrayBuffer());
    const actualHash = Array.from(new Uint8Array(digest), byte => byte.toString(16).padStart(2, '0')).join('');
    if (actualHash !== String(meta.sha256).toLowerCase()) throw new Error('SHA-256 校验失败，已取消保存');
    const objectUrl = URL.createObjectURL(blob);
    const anchor = document.createElement('a');
    anchor.href = objectUrl;
    anchor.download = 'syncdark-' + meta.versionName + '.apk';
    document.body.appendChild(anchor);
    anchor.click();
    anchor.remove();
    setTimeout(() => URL.revokeObjectURL(objectUrl), 60000);
    setProgress(100, '下载完成。请在通知栏或文件管理中打开 APK，并确认安装。', '下载完成');
  }

  const btn = $('#appInstall');
  if (btn) {
    btn.addEventListener('click', async () => {
      btn.disabled = true;
      try {
        if (pendingNativeInstaller && nativeUpdater && typeof nativeUpdater.installPending === 'function') {
          nativeUpdater.installPending();
          return;
        }
        const meta = latestApk || await loadApkVersion();
        if (installed && meta.versionCode < installed.versionCode) throw new Error('服务器安装包版本过旧，已阻止降级');
        if (nativeUpdater && typeof nativeUpdater.downloadAndInstall === 'function') {
          setProgress(0, '已连接 Android 原生更新器，准备下载并校验…', '正在准备更新');
          nativeUpdater.downloadAndInstall(new URL(meta.downloadUrl, location.origin).href, meta.sha256, meta.versionCode);
        } else {
          await browserDownload(meta);
        }
      } catch (error) {
        setProgress(0, error.message || '下载安装失败，请稍后重试', '下载未完成');
      } finally {
        btn.disabled = false;
      }
    });
  }

  const website = $('#appWebsite');
  if (website) website.addEventListener('click', () => window.open('/', '_self'));

  const refresh = $('#appRefresh');
  if (refresh) refresh.addEventListener('click', async () => {
    refresh.disabled = true;
    refresh.textContent = '正在检查…';
    installed = readInstalledVersion();
    latestApk = null;
    text('apkVersionInfo', '正在查询最新签名 APK 及完整性信息…');
    text('appVersionState', '正在检查更新…');
    try {
      await loadVersions();
      await loadApkVersion();
      if ('serviceWorker' in navigator) {
        const regs = await navigator.serviceWorker.getRegistrations();
        await Promise.all(regs.map(reg => reg.update().catch(() => {})));
      }
      refresh.textContent = '检查完成';
      const newer = installed && latestApk && latestApk.versionCode > installed.versionCode;
      text('appVersionState', newer
        ? '发现新版本：' + installed.versionName + ' → ' + latestApk.versionName
        : latestApk && installed && latestApk.versionCode === installed.versionCode
          ? '当前已是最新版本。'
          : latestApk && installed && latestApk.versionCode < installed.versionCode
            ? '服务器安装包版本更旧，已阻止降级。'
            : latestApk ? '最新 APK 版本信息已刷新。' : '未能取得 APK 版本信息。');
      refresh.textContent = '检查完成';
    } catch (error) {
      const message = error.message || '请检查网络';
      text('apkVersionInfo', '无法取得可用的签名 APK：' + message);
      text('appVersionState', '检查失败：' + message);
      text('appLatest', '暂无可用版本');
      text('apkVersionLabel', '暂不可用');
      text('apkBuildLabel', '—');
      text('apkSizeLabel', '—');
      setProgress(0, '检查失败，没有开始下载', '更新检查失败');
    } finally {
      refresh.disabled = false;
      refresh.textContent = '检查更新';
    }
  });

  text('appMode', nativeUpdater ? 'Android APK / 原生更新' : 'Android APK / 浏览器下载');
  installed = readInstalledVersion();
  loadVersions();
  loadApkVersion().catch(error => {
    const message = error.message || '版本接口暂不可用';
    text('apkVersionInfo', '无法取得可用的签名 APK：' + message);
    text('appVersionState', message);
    text('appLatest', '暂无可用版本');
    text('appUpdateText', '当前没有可验证并下载安装的签名 APK，或版本服务暂时不可用。请重新检查；不会伪造更新或下载成功。');
    text('apkVersionLabel', '暂不可用');
    text('apkBuildLabel', '—');
    text('apkSizeLabel', '—');
    setProgress(0, '尚无可验证的 APK；请稍后重新检查', '等待有效发布包');
  });
  window.addEventListener('pageshow', () => {
    installed = readInstalledVersion();
    loadVersions();
    loadApkVersion().catch(() => {});
  });
})();
